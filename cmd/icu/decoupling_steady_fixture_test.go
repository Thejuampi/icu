// fixtureServer serves testdata/fixtures read-only, the way icu-mock lays
// them out (/api/v1/<path> -> <path>.json); anything missing is [].
func fixtureServer(t *testing.T) *icu.Client {
	t.Helper()
	root, err := os.OpenRoot(filepath.Join("..", "..", "testdata", "fixtures"))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = root.Close() })
	server := httptest.NewServer(http.HandlerFunc(func(writer http.ResponseWriter, request *http.Request) {
		if request.Method != http.MethodGet {
			t.Errorf("non-GET %s %s", request.Method, request.URL.Path)
		}
		path := strings.TrimSuffix(strings.TrimPrefix(request.URL.Path, "/"), ".json")
		// os.Root confines reads to the fixture tree.
		if body, err := root.ReadFile(path + ".json"); err == nil {
			writer.Header().Set("Content-Type", "application/json")
			_, _ = writer.Write(body) //nolint:gosec // test-only JSON fixture from the confined root, served to the test client

			return
		}
		_, _ = writer.Write([]byte(`[]`))
	}))
	t.Cleanup(server.Close)

	return icu.NewClient("k", "0", icu.WithHTTPClient(server.Client()), icu.WithBaseURL(server.URL))
}

// i900000004 is generated by tools/steadyride (fixed seed): a 100 min steady
// Z2 ride with warm-up and cool-down ramps, HR delayed 45 s behind power plus 25 s smoothing
// (cross-correlation detects about 53 s), speed with inertia, no
// coasting, API decoupling 2.5. Every coach criterion passes, so the stream
// value is valid and consumed, and the summary keeps both values apart.
func TestSteadyRideFixtureIsValid(t *testing.T) {
	t.Parallel()
	out := runDecouplingCommand(t, fixtureServer(t), []string{"i900000004"}, map[string]string{decouplingSourceFlag: "streams"})
	failed, _ := out["failedCriteria"].([]any)
	summary, _ := out["summary"].(map[string]any)
	detail, _ := out["streamDetail"].(map[string]any)
	if out["validity"] != icu.DecouplingValid || len(failed) != 0 || out["streamsDecoupling"] != 0.32 ||
		detail["minutesKept"] != 74.0 || detail["hrLagMethod"] != "cross_correlation" {
		t.Fatalf("steady ride = validity %v failed %v value %v kept %v lag %v", out["validity"], out["failedCriteria"],
			out["streamsDecoupling"], detail["minutesKept"], detail["hrLagMethod"])
	}
	if lag, _ := detail["hrLagSeconds"].(float64); lag < 50 || lag > 56 {
		t.Fatalf("detected HR lag %v s, want about 53 s (see tools/steadyride hrLagSec)", detail["hrLagSeconds"])
	}
	// The consumed value is the stream one, but apiDecoupling must stay
	// intervals.icu's own value, top level and in the summary.
	if out["decoupling"] != 0.32 || out["apiDecoupling"] != 2.5 || summary["apiDecoupling"] != 2.5 || summary["streamsDecoupling"] != 0.32 {
		t.Fatalf("api/streams: top %v/%v summary %v/%v", out["apiDecoupling"], out["decoupling"], summary["apiDecoupling"], summary["streamsDecoupling"])
	}
}

// The help text is built from the Coach* constants (issue #35); pin the
// rendered thresholds so a formatting slip shows up here.
func TestActivityDecouplingDescriptionFromConstants(t *testing.T) {
	t.Parallel()
	got := activityDecouplingDescription()
	for _, want := range []string{
		"warm-up max(15 min,", "cut at 20 min", "cool-down 10 min", "VI <= 1.05 valid, 1.05-1.10 low confidence, > 1.10 not valid",
		">= 60 min; >= 85% of the time", "above 105% FTP", "coasting < 10%.",
		"< 5% good, 5-8% moderate, > 8% high; < -5% possible fatigue",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in %q", want, got)
		}
	}
}
